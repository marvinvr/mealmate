/// Playful default names for a new shopping list, prefilled in the "New List" alert (the user
/// can still type their own).
enum ShoppingListNames {
    /// A random name that isn't already taken (case-insensitive). When every one is taken, the
    /// name gets a number ("Basil Instinct 2").
    static func suggestion(avoiding existing: [String]) -> String {
        let taken = Set(existing.map { $0.trimmingCharacters(in: .whitespaces).lowercased() })
        if let name = all.filter({ !taken.contains($0.lowercased()) }).randomElement() {
            return name
        }
        let base = all.randomElement() ?? "Shopping List"
        let number = (2...).first { !taken.contains("\(base) \($0)".lowercased()) } ?? 2
        return "\(base) \(number)"
    }

